import { useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import { api } from '../api/client'
import { HBars, ChartCard, DataTable, TrendChart } from '../components/charts'
import { Delta, KpiCard } from '../components/Kpi'
import { SetupChecklist } from '../components/SetupChecklist'
import { Badge, Card, DemoBadge, Empty, ErrorNote, Note, PageHeader, Seg, SkeletonCard, SkeletonRows } from '../components/ui'
import { compactRupees, fmtQty, istTime, periodLabel, plural, rupees, unitLabel, wholeRupees } from '../lib/format'
import { useAuth } from '../lib/auth'
import { useAsync } from '../lib/hooks'
import { useDataScope } from '../lib/scope'
import { compareAov, comparePeriods } from '../lib/stats'

type Grain = 'day' | 'week' | 'month'
const PERIODS: Record<Grain, number> = { day: 30, week: 12, month: 12 }
const statusTone = { confirmed: 'info', fulfilled: 'ok', cancelled: 'bad' } as const

const greeting = () => { const h = new Date().getHours(); return h < 12 ? 'Good morning' : h < 17 ? 'Good afternoon' : 'Good evening' }

export default function Dashboard() {
  const { includeDemo } = useDataScope()
  const { user } = useAuth()
  const [grain, setGrain] = useState<Grain>('day')
  // `daily` feeds the KPI cards and sparklines; `trend` feeds the chart. For the daily view both are the same request (shared in flight).
  const daily = useAsync(() => api.salesSeries('day', 30, includeDemo), [includeDemo])
  const trend = useAsync(() => api.salesSeries(grain, PERIODS[grain], includeDemo), [grain, includeDemo])
  const stock = useAsync(() => api.inventorySummary(), [])
  const demand = useAsync(() => api.demand(30, includeDemo), [includeDemo])
  const ov = useAsync(() => api.overview(30, includeDemo), [includeDemo])
  const recent = useAsync(() => api.orders({ limit: 6, include_synthetic: includeDemo }), [includeDemo])

  const k = useMemo(() => {
    const s = daily.data?.series ?? []
    const rev = comparePeriods(s, 7, (p) => p.revenue_paise)
    const ord = comparePeriods(s, 7, (p) => p.orders)
    const done = s.filter((p) => !p.partial)
    const aov = compareAov(s, 7)
    const today = s[s.length - 1]
    return {
      rev, ord, aovNow: aov.cur, aovDelta: aov.delta,
      today: today && today.partial ? today : null,
      revSpark: done.slice(-14).map((p) => p.revenue_paise), ordSpark: done.slice(-14).map((p) => p.orders),
      aovSpark: done.slice(-14).map((p) => p.avg_basket_paise),
    }
  }, [daily.data])

  const attention = stock.data ? [...stock.data.out_of_stock.map((r) => ({ ...r, sev: 'out' as const })), ...stock.data.low_stock.map((r) => ({ ...r, sev: 'low' as const }))] : []
  const empty = daily.data && daily.data.totals.orders === 0
  const anyError = daily.error ?? trend.error ?? stock.error ?? ov.error

  return (
    <>
      <PageHeader title="Dashboard"
        description="How the shop is doing, from the orders and stock recorded in the database."
        meta={<Badge tone={includeDemo ? 'warn' : 'ok'} title="Use the Demo data switch in the top bar to change this">{includeDemo ? 'Includes generated demo data' : 'Only orders you recorded'}</Badge>}
        />

      <div className="stack">
        <ErrorNote error={anyError} onRetry={() => { daily.reload(); trend.reload(); stock.reload(); ov.reload() }} />
        {includeDemo && daily.data && (
          <Note tone="warn">
            <b>Demo data.</b> Past orders and customers on this shop are generated by <code>scripts/seed_db.py</code> so the charts have something to show. They are not real sales.
            Orders you take on the Order desk are saved here too and are counted as real.
          </Note>
        )}

        {user?.role === 'owner' && <SetupChecklist userId={user.id} prices={stock.data?.price_basis} realOrders={ov.data?.kpis.non_synthetic_orders_total} />}

        <section className="welcome" aria-label="Shop at a glance">
          <div className="welcome-hi"><h2>{greeting()}{user ? `, ${user.full_name.split(' ')[0]}` : ''}</h2><p className="muted small">The shop at a glance.</p></div>
          <div><span className="welcome-n">{recent.data ? recent.data.counts.all.toLocaleString('en-IN') : '-'}</span><span className="welcome-l">orders on record{includeDemo ? ', including demo' : ''}</span></div>
          <div><span className="welcome-n">{ov.data ? ov.data.kpis.today_orders.toLocaleString('en-IN') : '-'}</span><span className="welcome-l">orders today</span></div>
          <div><span className="welcome-n">{stock.data ? stock.data.stock_health.low + stock.data.stock_health.out : '-'}</span><span className="welcome-l">items to restock</span></div>
          <div className="welcome-go"><Link className="btn" to="/order">Take an order</Link>{user?.role === 'owner' && <Link className="btn secondary" to="/inventory">Manage stock</Link>}</div>
        </section>

        <div className="kpi-grid">
          <KpiCard label="Sales, last 7 days" icon="rupee" loading={daily.loading && !daily.data}
            value={wholeRupees(k.rev.cur)} spark={k.revSpark} sparkLabel="Daily sales, last 14 complete days"
            foot={<><Delta value={k.rev.delta} suffix="vs the 7 days before" />{k.today && <div>Today so far {wholeRupees(k.today.revenue_paise)}</div>}</>} />
          <KpiCard label="Orders, last 7 days" icon="orders" loading={daily.loading && !daily.data}
            value={k.ord.cur.toLocaleString('en-IN')} spark={k.ordSpark} sparkLabel="Daily orders, last 14 complete days"
            foot={<><Delta value={k.ord.delta} suffix="vs the 7 days before" />{k.today && <div>Today so far {plural(k.today.orders, 'order')}</div>}</>} />
          <KpiCard label="Average order value" icon="cart" loading={daily.loading && !daily.data}
            value={wholeRupees(k.aovNow)} spark={k.aovSpark} sparkLabel="Average bill per day, last 14 complete days"
            foot={<Delta value={k.aovDelta} suffix="vs the 7 days before" />} />
          <KpiCard label="Needs restocking" icon="alert" loading={stock.loading && !stock.data}
            value={stock.data ? stock.data.stock_health.low + stock.data.stock_health.out : '-'}
            foot={stock.data ? <span>{stock.data.stock_health.out} finished · {stock.data.stock_health.low} running low · <Link to="/inventory?status=low">Review</Link></span> : null} />
        </div>

        <div className="dash-grid">
          <ChartCard className="fill" title="Sales trend" sub={empty ? undefined : `${grain === 'day' ? 'Last 30 days' : grain === 'week' ? 'Last 12 weeks' : 'Last 12 months'}. Cancelled orders excluded.`}
            actions={<Seg label="Time grouping" value={grain} onChange={setGrain} options={[{ value: 'day', label: 'Daily' }, { value: 'week', label: 'Weekly' }, { value: 'month', label: 'Monthly' }]} />}
            table={<DataTable head={['Period', 'Sales', 'Orders', 'Average bill']} rows={(trend.data?.series ?? []).map((p) => [periodLabel(p.period, grain) + (p.partial ? ' (in progress)' : ''), rupees(p.revenue_paise), p.orders, rupees(p.avg_basket_paise)])} />}
            legend={trend.data?.series.some((p) => p.partial) ? <span>{grain === 'day' ? 'Dashed line: today so far, not a full day' : 'Hatched bar: period still in progress'}</span> : undefined}>
            {trend.loading && !trend.data ? <SkeletonCard lines={5} height={280} /> : empty ? (
              <Empty title="No orders in this period" icon="chart" action={<Link className="btn" to="/order">Take the first order</Link>}>
                {includeDemo ? 'Seed the demo data with scripts/seed_db.py, or take an order on the Order desk.' : 'Demo data is switched off. Orders you take on the Order desk will appear here.'}
              </Empty>
            ) : trend.data ? <TrendChart series={trend.data.series} grain={grain} fill /> : null}
          </ChartCard>

          <Card title="Restock now" description="Items at or below their alert level" actions={<Link className="btn secondary small" to="/inventory?status=low">All stock</Link>}>
            {stock.loading && !stock.data ? <SkeletonRows rows={5} cols={2} /> : attention.length === 0 ? (
              <Empty title="Everything is stocked" icon="check">No item is at or below its alert level.</Empty>
            ) : (
              <ul className="list-rows">
                {attention.slice(0, 7).map((r) => (
                  <li key={r.product_id}>
                    <span className="grow truncate"><b style={{ fontWeight: 550 }}>{r.name}</b></span>
                    <span className="faint small nowrap">{r.sev === 'out' ? '' : `${fmtQty(r.stock)} ${unitLabel(r.unit)} left`}</span>
                    <Badge tone={r.sev === 'out' ? 'bad' : 'warn'}>{r.sev === 'out' ? 'Finished' : 'Low'}</Badge>
                  </li>
                ))}
              </ul>
            )}
            {attention.length > 7 && <p className="small muted" style={{ margin: '10px 0 0' }}>and {attention.length - 7} more. <Link to="/inventory?status=low">See all</Link></p>}
            {demand.data && demand.data.stockout_risk.length > 0 && (
              <>
                <hr className="divider" />
                <h3 className="small muted" style={{ fontWeight: 600, marginBottom: 8 }}>Selling fast, may run out within 3 days</h3>
                <ul className="list-rows">
                  {demand.data.stockout_risk.slice(0, 3).map((r) => (
                    <li key={r.product_id}><span className="grow truncate">{r.name}</span><span className="small muted nowrap">{r.days_of_cover} days of stock</span></li>
                  ))}
                </ul>
              </>
            )}
          </Card>
        </div>

        <div className="cols even">
          <ChartCard className="fill" title="Best sellers" sub="By sales, last 30 days"
            table={<DataTable head={['Product', 'Sales', 'Quantity']} rows={(ov.data?.top_products ?? []).map((x) => [x.name, rupees(x.revenue_paise), `${Math.round(x.qty * 10) / 10} ${unitLabel(x.unit)}`])} />}>
            {ov.loading && !ov.data ? <SkeletonCard lines={5} height={220} /> : ov.data && ov.data.top_products.length ? (
              <HBars rows={ov.data.top_products.slice(0, 8).map((x) => ({ name: x.name, v: x.revenue_paise }))} fmt={compactRupees} labelWidth={150} fill />
            ) : <Empty title="No sales yet" icon="chart" />}
          </ChartCard>

          <Card title="Recent orders" description="Newest first" actions={<Link className="btn secondary small" to="/orders">All orders</Link>} flush>
            {recent.loading && !recent.data ? <SkeletonRows rows={5} cols={3} /> : recent.data && recent.data.items.length ? (
              <div className="table-wrap">
                <table className="tbl compact">
                  <thead><tr><th>Order</th><th>When</th><th className="num">Total</th><th>Status</th></tr></thead>
                  <tbody>
                    {recent.data.items.map((o) => (
                      <tr key={o.id}>
                        <td><Link to={`/orders?open=${o.id}`} className="mono-id">{o.code}</Link>{o.is_synthetic && <> <DemoBadge /></>}<span className="sub">{o.customer_name}</span></td>
                        <td className="muted nowrap">{istTime(o.created_at)}</td>
                        <td className="num"><b>{rupees(o.total_paise)}</b></td>
                        <td><Badge tone={statusTone[o.status]}>{o.status}</Badge></td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            ) : <Empty title="No orders yet" icon="orders" action={<Link className="btn secondary" to="/order">Open the Order desk</Link>} />}
          </Card>
        </div>
      </div>
    </>
  )
}
